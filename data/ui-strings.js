/** Languages that have a full static translation, so no model call is needed. */
export function hasStatic(code, keys) {
  const table = UI_STRINGS[code];
  if (!table) return false;
  return keys.every((k) => typeof table[k] === 'string' && table[k].length > 0);
}

/** Static translation for `keys`, falling back to the English text per key. */
export function staticStrings(code, strings) {
  const table = UI_STRINGS[code] || {};
  return Object.fromEntries(Object.keys(strings).map((k) => [k, table[k] ?? strings[k]]));
}
