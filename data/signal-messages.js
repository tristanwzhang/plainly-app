/** Fill {placeholders}. An unknown placeholder is left as-is rather than blanked. */
export function fill(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** One message in `lang`, falling back to English when that language lacks it. */
export function message(lang, id, vars) {
  const table = MESSAGES[lang] || MESSAGES.en;
  return fill(table[id] ?? MESSAGES.en[id] ?? '', vars);
}

/** A kind label in `lang`, falling back to English. */
export function kindLabel(lang, key) {
  const table = KINDS[lang] || KINDS.en;
  return table[key] ?? KINDS.en[key] ?? KINDS.en.letter;
}
